// In-memory mock orders storage (cleared on server restart, ready for DB)
let mockOrders: Order[] = [];

export function getMockOrders(): Order[] {
  return mockOrders;
}

export function addMockOrder(order: Order): void {
  mockOrders = [order, ...mockOrders];
}

export function updateMockOrderStatus(
  orderNumber: string,
  paymentStatus: Order["paymentStatus"]
): Order | null {
  const idx = mockOrders.findIndex((o) => o.orderNumber === orderNumber);
  if (idx === -1) return null;
  mockOrders[idx] = { ...mockOrders[idx], paymentStatus };
  return mockOrders[idx];
}

export function getMockOrderByNumber(orderNumber: string): Order | undefined {
  return mockOrders.find((o) => o.orderNumber === orderNumber);
}

let orderCounter = 1;

export function generateOrderNumber(): string {
  const year = new Date().getFullYear();
  const num = String(orderCounter++).padStart(4, "0");
  return `DM-${year}-${num}`;
}
